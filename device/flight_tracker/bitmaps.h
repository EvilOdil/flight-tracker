// Family key (sent by backend as "fam") -> bitmap. Unknown keys fall back to
// the A330 silhouette as a generic airliner shape until more art is added.
struct AircraftBitmap {
  const char* fam;
  const unsigned char* bmp;
};

const AircraftBitmap AIRCRAFT_BITMAPS[] = {
  { "B737", b737_bmp },
  { "B747", b737_bmp },  // TODO: dedicated widebody-Boeing bitmap
  { "A320", a330_bmp },  // TODO: dedicated A320 bitmap
  { "A330", a330_bmp },
  { "RJ",   b737_bmp },  // TODO: regional-jet bitmap
  { "PROP", a330_bmp },  // TODO: turboprop bitmap
  { "GA",   a330_bmp },  // TODO: general-aviation bitmap
};

inline const unsigned char* bitmapForFamily(const String& fam) {
  for (const auto& e : AIRCRAFT_BITMAPS) {
    if (fam == e.fam) return e.bmp;
  }
  return a330_bmp;  // GENERIC fallback
}
